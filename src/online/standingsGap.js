// ============================================================
// 順位表のゲーム差（先方要望 2026-11-20「上位順位のチームとのゲーム差を、勝率と打率の間に」）。
//
// ⚠ **すぐ上の順位の球団との差**（NPB の順位表の「差」と同じ）。首位との差ではない。
//    1位は「—」。勝ち越し数の差の半分: ((上の勝 − 勝) + (敗 − 上の敗)) / 2。引き分けは数えない。
// ⚠ 並びは呼ぶ側で決める（部ごと・`compareLeagueStanding` の順）。ここは並んだ行を読むだけ。
//    勝率で並べるので、勝率が上でも勝ち越し数が少ない球団は差がマイナスになることがある（NPB と同じ）。
// ============================================================

/** 並んだ行（勝・敗を持つ）の、それぞれすぐ上の球団とのゲーム差。1位は null */
export function gamesBehind(rows = []) {
  return rows.map((row, i) => {
    if (i === 0) return null;
    const above = rows[i - 1];
    return ((above.wins || 0) - (row.wins || 0) + ((row.losses || 0) - (above.losses || 0))) / 2;
  });
}

/** 差の見せ方。「—」・「0.0」・「1.5」・「-0.5」（アプリの順位表 `LeagueBoards.kt` と同じ小数1桁） */
export function gapText(gap) {
  if (gap == null) return '—';
  return (gap === 0 ? 0 : gap).toFixed(1);
}
