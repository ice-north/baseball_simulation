import { createContext, useContext } from 'react';

// ============================================================
// 画面の奥から命令を送るための受け渡し。
//
// 【なぜ要るか】選手の詳細（`PlayerStatsButton`）は、選手成績・通算成績・
// スタメン設定・投手起用・トレード・能力ランキングと**10か所以上**から開かれる。
// 守備位置の変更のような「詳細の中からサーバーへ送る操作」のために
// `view` / `run` / `command` を全部の呼び出しへ引き回すと、途中の部品が
// 中身を知らないまま持ち回ることになる。
//
// ⚠ **これを増やしすぎないこと**。ページ本体へ渡せるものはプロップで渡す。
//    ここに入れるのは「どこから開かれるか分からない小窓」が使うものだけ。
// ⚠ 包んでいないところ（検査の fixture など）では `null` が返る。使う側は
//    無いときに操作を**出さない**（出して押せないより、出さないほうがよい）。
// ============================================================
export const ActionContext = createContext(null);

/** `{ teamName, writable, busy, run, command }`。包まれていなければ null */
export const useActions = () => useContext(ActionContext);
