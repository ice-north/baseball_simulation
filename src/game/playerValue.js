// ============================================================
// 選手の価値を1つの物差しに揃える - playerValue.js
//
// 【なぜ必要か】投手と野手の評価点が**別々のスケール**で作られていた。
// 実測（高校生プール）で 能力点の平均が 投手94 / 捕手129 / 野手135 と揃っておらず、
// ドラフト上位120人の構成が **投手2% / 捕手4% / 野手94%**（実NPBは概ね
// 投手55% / 捕手8% / 野手37%）という状態だった。
// トレードも同じで、`TradeScreen` は独自の式を持っていて三重の物差しになっていた。
//
// 【1点あたりの価値を実測して合わせる】
// リーグ全体の投手／野手を一律に強化し、防御率がどれだけ動くかで換算する
// （同一ロスター反復8シード×120試合）:
//   全投手を強化 … 防御率 -0.385 ± 0.041（能力点 +18.7pt）→ 1pt = 0.0206
//   全野手を強化 … 防御率 +0.870 ± 0.023（能力点 +24.5pt）→ 1pt = 0.0354
// → **投手1pt は野手1pt の 1.72倍の価値**。
// チーム横断の回帰（48チーム）でも 1.81 と出ており、2つの方法が一致している。
//
// ⚠ **倍率だけ掛けてはいけない**。能力点のゼロ点が投打で対応していないため、
// 絶対値を1.72倍すると上位120人が **投手94%** になって逆に壊れる。
// **ポジション群ごとに平均を引いてから**倍率を掛けること
// （＝「同じポジションの中でどれだけ抜けているか」を揃える。スカウトの20-80と同じ考え方）。
// ============================================================

/** ポジション群。捕手はリード・フレーミングがあるので野手と分ける */
export const valueGroup = (player) =>
  player?.position === 'pitcher' ? 'P'
    : player?.position === 'catcher' ? 'C' : 'F';

// 群 × 年齢帯 ごとの能力点の平均（リーグロスター＋高校生プール＋大学プールで実測）。
//
// ⚠ **年齢帯ごとに持つこと**。`draftAbilityScore` は 高校生(isYoung) と
// 社会人(isMature) で別のウェイトを使う（球速×1.5 対 0.9、制球×0.7 対 1.4 …）ので、
// 素点のスケールが年齢帯で違う。高校生プールで測った1組の平均を全年齢に当てると
// **指名ソースの構成が壊れる**（実際に 高校62%→4% / 独立11%→37% になった）。
// ⚠ 選手生成やウェイトを触ったら測り直すこと。
export const AGE_BAND = (age = 20) => (age <= 19 ? 'young' : age >= 22 ? 'mature' : 'mid');
export const VALUE_MEAN = {
  'P|young': 79, 'P|mid': 148, 'P|mature': 187,
  'C|young': 108, 'C|mid': 168, 'C|mature': 201,
  'F|young': 113, 'F|mid': 173, 'F|mature': 201,
};

// 群ごとの「1点あたりの価値」の倍率。
//
// ⚠ **まだ 1.0 のまま**。実測では 野手1pt = 0.0354 / 投手1pt = 0.0206 で
// 野手の1点が 1.72倍の価値だが、**単一の倍率では直せない**ことが分かった:
//   投手ブランチの内部の重みがそもそもずれている。球速は実測 1km = 0.0512 防御率
//   なのにスコア寄与は 0.9pt しかなく（1pt = 0.057）、ブランチ平均の 0.0206 に対して
//   **2.8倍の過小評価**。制球・スタミナ・変化球が相対的に効きすぎている。
// 倍率だけ掛けると「過小評価された球速」を抱えたまま全体をずらすことになる。
// 正しくは球種スコアと同じように、**能力ごとの重みを実測に回帰して求め直す**こと。
// それまでは 1.0 にしておき、少なくとも**式が1本である**ことだけを担保する。
export const VALUE_MULT = { P: 1.0, C: 1.0, F: 1.0 };

/**
 * 能力点を**投打で比較可能な価値**に変換する。
 * 0 = そのポジションの平均的な選手。正なら平均より上。
 */
export function toCommonValue(player, abilityScore) {
  const g = valueGroup(player);
  const mean = VALUE_MEAN[`${g}|${AGE_BAND(player?.age)}`] ?? 0;
  return (abilityScore - mean) * VALUE_MULT[g];
}
