// ============================================================
// 選手の価値を1つの物差しに揃える - playerValue.js
//
// 【なぜ必要か】トレード（`TradeScreen` のローカル `getPlayerValue`）と
// ドラフト（`checkNPBDraftEligibility`）が**別々の評価式**を持っていた。
// 式が違えば等価交換にならないし、投手と野手の素点のスケールも揃っていなかった
// （実測: 上位120人の構成が 投手2% / 捕手4% / 野手94%）。
// 能力点を `draftAbilityScore` に一本化し、ここで投打を比較可能な形にする。
// **独自の評価式をもう1つ書かないこと**。
//
// 【メイン／サブに分ける】
//   メイン（スカウトが最初に見る中核）
//     投手 … 球速・制球・変化球
//     野手 … 打撃（ミート/パワー/選球眼）・守備・走塁（捕手はリードも守備の一部）
//   サブ（メインを支えるフィジカルと付随要素）
//     投手 … スタミナ・体力・素材としての肩・フォーム
//     野手 … 肩・体力・守備の幅
//
// 【投打は「群ごとの偏差値」で比べる】
// 素点のスケールを倍率で揃えようとして**2通り失敗した**:
//   1. 実測の1ptあたりの価値（野手0.0354 / 投手0.0206 ＝ 野手が1.72倍）を
//      **絶対値に掛ける** → ゼロ点が投打で対応しておらず上位120人が**投手94%**
//   2. **平均を引いてから掛ける** → `draftAbilityScore` は年齢帯で別ウェイトを
//      使う（球速×1.5 対 0.9 …）ため素点のスケールが年齢帯で違い、
//      指名ソースの構成が壊れる（**高校62%→4%**）
// 偏差値ならゼロ点も年齢帯のスケール差も関係なくなる。
// 「同じポジションの中でどれだけ抜けているか」で比べるのは、
// スカウトの 20-80 スケールと同じ考え方でもある。
// ============================================================

/** ポジション群。捕手はリード・フレーミングがあるので野手と分ける */
export const valueGroup = (player) =>
  player?.position === 'pitcher' ? 'P'
    : player?.position === 'catcher' ? 'C' : 'F';

export const AGE_BAND = (age = 20) => (age <= 19 ? 'young' : age >= 22 ? 'mature' : 'mid');

// メインとサブの重み。メインは「スカウトが最初に見る」ものなので厚く。
const W_MAIN = 1.0;
const W_SUB = 0.6;

// 群ごとの素点（main + sub×W_SUB）の平均。
// リーグロスター＋高校生プール＋大学プールで実測。
//
// ⚠ **平均は年齢帯で分けないこと**。分けると各帯の平均が50になり、
// ソース構成が `ageBonus` だけで決まって高校生に偏る（実測 **高校84%**）。
// 年齢による水準の差は素点に残したまま、群だけで標準化する。
// 将来性は `ageBonus`/`potentialMult` が別に見る、という分業。
// ⚠ **才能オフセット・大学の成長・投手の生成率を変えたら必ず測り直すこと**。
//    設定より実測σが大きいと偏差が水増しされ、その群の上位が膨らむ。
//    実際、投手の生成率を 41%→51% にした後に測ると 実測131/60 対 設定109/46 で、
//    投手の指名シェアがプール比率より6pt高く出ていた。
export const VALUE_DIST = {
  P: { mean: 131, sd: 60 },
  C: { mean: 122, sd: 42 },
  F: { mean: 127, sd: 42 },
};

// ⚠ **σは年齢帯ごとに持つこと**。年齢帯で幅が違う（高校生投手32 / 社会人投手34 など）ので、
// 群共通のσで標準化すると高校生投手だけ偏差値が伸びない
// （上位120人の投手がプール比率42%に対して**20%**しか入らなかった）。
// 「年齢による水準の差は残し、幅だけ揃える」のが正しい切り分け。
export const BAND_SD = {
  'P|young': 31, 'P|mid': 40, 'P|mature': 56,
  'C|young': 25, 'C|mid': 28, 'C|mature': 44,
  'F|young': 23, 'F|mid': 28, 'F|mature': 45,
};

// 偏差値をドラフト評価の桁に合わせる係数。
// 従来の能力点は σ 25〜30 程度だったので、偏差値(σ10)を約3倍して揃える。
const DEV_SCALE = 3.0;

function devOf(g, age, raw) {
  const mean = (VALUE_DIST[g] || VALUE_DIST.F).mean;
  const sd = BAND_SD[`${g}|${AGE_BAND(age)}`] || (VALUE_DIST[g] || VALUE_DIST.F).sd;
  return 50 + 10 * (raw - mean) / (sd || 1);
}

/**
 * メイン／サブから、**投打で比較できる**評価点を作る。
 * 群ごとの偏差値 × 3。平均的な選手が 150 になる。
 */
export function deviationValue(player, main, sub) {
  return devOf(valueGroup(player), player?.age, main * W_MAIN + sub * W_SUB) * DEV_SCALE;
}

/**
 * 偏差値そのもの（平均50・σ10）。
 * 成長力ボーナスの倍率など、**素点で割ってはいけない**場所で使う
 * （素点だと投手(平均81)と野手(平均113)で倍率が変わり、揃えたスケールがずれる）。
 */
export function deviationOf(player, main, sub) {
  return devOf(valueGroup(player), player?.age, main * W_MAIN + sub * W_SUB);
}

/** 素点（偏差値にする前）。上の VALUE_DIST / BAND_SD を測り直すときに使う */
export function rawAbilityOf(main, sub) { return main * W_MAIN + sub * W_SUB; }

// ============================================================
// ドラフトのロスター需要（**価値ではない**）
//
// 純粋な価値で並べると 投手39% / 捕手3% / 野手58% になる。
// 実NPBが投手を多く獲るのは1人あたりの価値が高いからではなく、
//   ・1軍に投手が11〜13人必要（野手は9＋控え）
//   ・野手転向を前提にした指名もある
//   ・捕手は2人必要だが母数が少ない
// という**ロスター需要**の話。価値の物差しを歪めずにここで表現する。
//
// ⚠ **ドラフト（と将来性を見る画面）にだけ掛けること**。
// トレードの等価交換は `deviationValue` をそのまま使う——需要を混ぜると
// 「同じ数値なら等価」が崩れる。
// 較正: 投手と野手が概ね半々、捕手が実NPB並みの8%前後になる値。
// ============================================================
// ⚠ **撤廃済み（すべて0）**。投手・捕手の比率は**母集団**（高校生プールの生成率）
// で作るようにした。`deviationValue` が群ごとに偏差値化しているので、加点が無ければ
// **指名比率はプール比率にほぼ一致する**（実測 プール投手41% → 指名41%）。
// 生成率を 投手50% / 捕手7.5% に合わせてあるので、ここで寄せる必要が無くなった。
// ⚠ ここに数字を戻さないこと——価値の物差しが歪み、トレードの等価交換とも食い違う。
export const DRAFT_DEMAND = { P: 0, C: 0, F: 0 };
