// その県の高校の選手が県の表から姓を引く確率。
// ⚠ **1.0 にしない**。上位500で県人口の 87.1% を占めるが、残り 12.9% の裾は
//    **それ自体が沖縄の姓**（勢理客級より珍しいもの）で、こちらは表を持っていない。
//    1.0 にするとその質量が上位500へ再配分されて上が濃くなりすぎる。
// ⚠ **本土の姓を混ぜるための値ではない**。表そのものが 佐藤(316位) 鈴木(381位)
//    高橋(377位) 井上(306位) 伊藤(358位) 渡辺(488位) を**県内の正しい人数で
//    含んでいる**ので、本土からの移住分はこの表だけで再現できる
//    （本土でも上位の姓は41件・5.9%のシェア）。
export const REGIONAL_SHARE = 0.92;

const CACHE = {};
const weighted = (pref) => {
  if (CACHE[pref]) return CACHE[pref];
  const rows = PREFECTURE_SURNAME_POP[pref];
  if (!rows) return null;
  const total = rows.reduce((s, r) => s + r[1], 0);
  // 重みは県内シェア(%)。playerNames の全国の物差しとは別系統だが、
  // この表だけで正規化して引くので混ざらない
  CACHE[pref] = rows.map(([name, pop]) => ({ name, weight: pop / total * 100 }));
  return CACHE[pref];
};

/** その県の表から姓を引く。表を持たない県は null（呼び出し側が全国へ落とす） */
export function getRegionalSurname(pref) {
  const items = weighted(pref);
  if (!items) return null;
  let r = Math.random() * 100;
  for (const it of items) { r -= it.weight; if (r <= 0) return it.name; }
  return items[items.length - 1].name;
}

/** 県の表を持っているか */
export const hasRegionalSurnames = (pref) => !!PREFECTURE_SURNAME_POP[pref];
