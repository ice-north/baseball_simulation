// 才能ランクに応じた出身校割り当て
// 相関はあるが決定的ではない。F校でもB〜C才能が数%混ざり、
// 大学・社会人で揉まれればプロを目指せる
export function assignHighSchool(talentTier) {
  const pools = {
  // ⚠ 各ランクは1行に1回だけ。以前は B〜E 行の末尾が `['D', n]` と重複しており
  // （S/A 行は S〜F を1回ずつで重複なし）、**才能E層の68%がDランク校**に
  // 割り当てられていた。重みが 4→15→37→66 と才能が下がるほど増える形なので
  // 「最も弱い校」の枠のはずで、ランク文字の誤記。F に統合してある。
  // 直す前は D校が1校あたり40.6人・F校が26.9人と非単調だった。
  // 【強豪校にも落ちこぼれはいる】才能に対して**3ランク上の校まで**届かせる。
  // 以前は各行に「才能の上限」があり（才能Cは C校より上へ行けない等）、
  // **校名を見ればS校の選手はA才能以上と確定で分かって**しまっていた。
  // 1ランク上は既存の 2〜3、2ランク上=1.2 / 3ランク上=0.4 と減衰する裾を足す
  // （足したぶんは各行の F から引いて合計100に戻す）。
  // 下向き（弱小校の逸材）は従来どおり制限しない——S才能の1%はF校から出る。
    S: [['S', 35], ['A', 28], ['B', 18], ['C', 10], ['D', 5], ['E', 3], ['F', 1]],
    A: [['S', 8], ['A', 30], ['B', 28], ['C', 18], ['D', 8], ['E', 5], ['F', 3]],
    B: [['S', 1.2], ['A', 3], ['B', 20], ['C', 28], ['D', 24], ['E', 13], ['F', 10.8]],
    C: [['S', 0.4], ['A', 1.2], ['B', 2], ['C', 15], ['D', 25], ['E', 25], ['F', 31.4]],
    D: [['A', 0.4], ['B', 1.2], ['C', 2], ['D', 12], ['E', 22], ['F', 62.4]],
    E: [['B', 0.4], ['C', 1.2], ['D', 2], ['E', 10], ['F', 86.4]],
  };
  const dist = pools[talentTier] || pools['D'];
  let roll = Math.random() * 100;
  for (const [rank, weight] of dist) {
    roll -= weight;
    if (roll <= 0) {
      const list = BY_RANK[rank];
      const school = list[Math.floor(Math.random() * list.length)];
      return { name: school.name, rank: school.rank, pref: school.pref };
    }
  }
  const fallback = BY_RANK['D'];
  const s = fallback[Math.floor(Math.random() * fallback.length)];
  return { name: s.name, rank: s.rank, pref: s.pref };
}
