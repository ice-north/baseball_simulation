// 実在の高校名に多い接尾辞。空文字＝地名そのまま（「米子西」ではなく「米子」）
const SUFFIX = ['', '工業', '商業', '東', '西', '南', '北', '農業',
  '第一', '中央', '実業', '第二', '総合', '工科', '農林'];

// 県ごとの目標校数。実在校の分布（大阪16〜福島1）をそのまま拡大し、
// 少ない県でも県予選が成立するよう下限を設ける
const PREF_MULT = 3.1;
const PREF_MIN = 10;

// 足す校のランク配分。実測の所属人数（D 559 / E 864 / F 3020）に合わせて
// F を最も多くする。i で決まるので生成は決定的
const genRank = (i) => (i % 14 === 0 ? 'D' : i % 6 === 1 ? 'E' : 'F');

const GENERATED = [];
{
  const existing = new Set(RAW.map(r => r[0]));
  const byPref = {};
  for (const [, , pref] of RAW) byPref[pref] = (byPref[pref] || 0) + 1;
  let i = 0;
  for (const pref of Object.keys(PLACES)) {
    const target = Math.max(PREF_MIN, Math.round((byPref[pref] || 0) * PREF_MULT));
    const need = target - (byPref[pref] || 0);
    const places = PLACES[pref];
    let made = 0;
    // 接尾辞を外側に回すと「◯◯工業」ばかりの県にならず、地名が先に出そろう
    for (let s = 0; s < SUFFIX.length && made < need; s++) {
      for (let p = 0; p < places.length && made < need; p++) {
        const name = places[p] + SUFFIX[s];
        if (existing.has(name)) continue;
        existing.add(name);
        GENERATED.push([name, genRank(i++), pref]);
        made++;
      }
    }
  }
}

const ALL = RAW.concat(GENERATED);

const BY_RANK = {};
for (const [name, rank, pref] of ALL) {
  if (!BY_RANK[rank]) BY_RANK[rank] = [];
  BY_RANK[rank].push({ name, rank, pref });
}

const LOOKUP = {};
for (const [name, rank, pref] of ALL) {
  LOOKUP[name] = { name, rank, pref };
}

export const HIGH_SCHOOL_BY_RANK = BY_RANK;
export const HIGH_SCHOOL_LOOKUP = LOOKUP;
export const HIGH_SCHOOL_COUNT = ALL.length;
export const HIGH_SCHOOL_REAL_COUNT = RAW.length;

// 才能ランクに応じた出身校割り当て
// 相関はあるが決定的ではない。F校でもB〜C才能が数%混ざり、
// 大学・社会人で揉まれればプロを目指せる
export function assignHighSchool(talentTier) {
  const pools = {
  // ⚠ 各ランクは1行に1回だけ。以前は B〜E 行の末尾が `['D', n]` と重複しており
  // （S/A 行は S〜F を1回ずつで重複なし）、**才能E層の68%がDランク校**に
  // 割り当てられていた。重みが 4→15→37→66 と才能が下がるほど増える形なので
  // 「最も弱い校」の枠のはずで、ランク文字の誤記。F に統合してある。
  // 直す前は D校が1校あたり40.6人・F校が26.9人と非単調だった。
    S: [['S', 35], ['A', 28], ['B', 18], ['C', 10], ['D', 5], ['E', 3], ['F', 1]],
    A: [['S', 8], ['A', 30], ['B', 28], ['C', 18], ['D', 8], ['E', 5], ['F', 3]],
    B: [['A', 3], ['B', 20], ['C', 28], ['D', 24], ['E', 13], ['F', 12]],
    C: [['B', 2], ['C', 15], ['D', 25], ['E', 25], ['F', 33]],
    D: [['C', 2], ['D', 12], ['E', 22], ['F', 64]],
    E: [['D', 2], ['E', 10], ['F', 88]],
  };
  const dist = pools[talentTier] || pools['D'];
  let roll = Math.random() * 100;
  for (const [rank, weight] of dist) {
    roll -= weight;
    if (roll <= 0) {
      const list = BY_RANK[rank];
      const school = list[Math.floor(Math.random() * list.length)];
      return { name: school.name, rank: school.rank, pref: school.pref };
    }
  }
  const fallback = BY_RANK['D'];
  const s = fallback[Math.floor(Math.random() * fallback.length)];
  return { name: s.name, rank: s.rank, pref: s.pref };
}
